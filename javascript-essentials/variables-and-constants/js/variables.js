// How to create variables 

/*
3 types of variables 

1. Var : Old Style (Not Used)

2. Let 

3. Const 



*/
// 1. Using Var 
var name = "Mamun"
name = "Joy"

console.log(name)

// 2. Using Let (When Value Change)  

let age = 25;
console.log(age)

age = 30

console.log(age)

// 3. Using Const (Used for fixed value ) 
const Country = "Bangladesh"
const Country2 = "USA"
console.log(Country)
console.log(Country2)


